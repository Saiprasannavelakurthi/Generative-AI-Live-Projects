import re
from services.babel_service import validate_with_babel


def validate_component(code):
    """
    Validate the React component generated by the AI.
    """

    # ----------------------------------------
    # Empty response
    # ----------------------------------------
    if not code or not code.strip():
        return False, "Error: Empty response from AI."

    code = code.strip()

    # ----------------------------------------
    # Remove markdown automatically
    # ----------------------------------------
    code = re.sub(r"^```[a-zA-Z]*", "", code)
    code = re.sub(r"```$", "", code)
    code = code.strip()

    # ----------------------------------------
    # Component name
    # ----------------------------------------
    if not (
        re.search(r"const\s+Component\s*=", code)
        or re.search(r"function\s+Component\s*\(", code)
    ):
        return False, "Error: Root component must be named Component."

    # ----------------------------------------
    # JSX return
    # ----------------------------------------
    if "return" not in code:
        return False, "Error: JSX return statement not found."

    # ----------------------------------------
    # Imports
    # ----------------------------------------
    if re.search(r"^\s*import\s", code, re.MULTILINE):
        return False, "Error: Import statements are not allowed."

    # ----------------------------------------
    # Exports
    # ----------------------------------------
    if re.search(r"^\s*export\s", code, re.MULTILINE):
        return False, "Error: Export statements are not allowed."

    # ----------------------------------------
    # Braces
    # ----------------------------------------
    if code.count("{") != code.count("}"):
        return False, "Error: Unbalanced braces."

    # ----------------------------------------
    # Parentheses
    # ----------------------------------------
    if code.count("(") != code.count(")"):
        return False, "Error: Unbalanced parentheses."

    # ----------------------------------------
    # Babel Validation
    # ----------------------------------------
    babel_result = validate_with_babel(code)

    if not babel_result.get("valid", False):
        return (
            False,
            f"Babel validation failed: {babel_result.get('message', 'Unknown error')}"
        )

    return True, "React component is valid."


