import re
from services.babel_service import validate_with_babel


def ensure_component_wrapper(code: str) -> str:
    """
    Ensures that the code defines a root React component function named Component.
    If it defines a component with another name (e.g., LoginUI, DashboardUI), renames it to Component.
    If it is bare JSX with no component declaration, wraps it in const Component = () => { return ( ... ); };.
    """
    if not code or not code.strip():
        return code

    code = code.strip()

    # Already has Component definition
    if (
        re.search(r"const\s+Component\s*=", code)
        or re.search(r"function\s+Component\s*\(", code)
    ):
        return code

    # Check if another component function/const was defined (e.g. const LoginCard = ...)
    match = re.search(r"(?:const|function)\s+([A-Z][a-zA-Z0-9_]*)\s*(?:=|\()", code)
    if match and match.group(1) not in ("React", "Fragment", "Component"):
        root_name = match.group(1)
        return re.sub(rf"\b{root_name}\b", "Component", code)

    # Bare JSX snippet — wrap in Component
    return f"const Component = () => {{\n    return (\n{code}\n    );\n}};"


def clean_code(code: str) -> str:
    """
    Clean raw LLM generated code by stripping Markdown code block wrappers,
    leading/trailing backticks, import statements, and export statements.
    """
    if not code:
        return ""

    cleaned = code.strip()

    # Remove leading markdown code block start e.g. ```jsx, ```javascript, ```react, ```
    cleaned = re.sub(r"^```[a-zA-Z]*\s*", "", cleaned)

    # Remove trailing markdown code block end e.g. ```
    cleaned = re.sub(r"\s*```$", "", cleaned)

    # Remove any line that is just ```
    cleaned = re.sub(r"^```\s*$", "", cleaned, flags=re.MULTILINE)

    # Strip import statements
    cleaned = re.sub(r"^\s*import\s+.*?;?\s*$", "", cleaned, flags=re.MULTILINE)

    # Strip export statements
    cleaned = re.sub(r"^\s*export\s+(?:default\s+)?.*?;?\s*$", "", cleaned, flags=re.MULTILINE)

    # Fix spaced variable typos e.g. Form Data -> formData
    cleaned = re.sub(r"\bForm\s+Data\b", "formData", cleaned, flags=re.IGNORECASE)

    # Safe optional chaining for chained .split() array access
    cleaned = re.sub(r"\.split\(([^)]+)\)\[(\d+)\]\.split\(", r"?.split(\1)?[\2]?.split(", cleaned)
    cleaned = re.sub(r"\.split\(([^)]+)\)\[(\d+)\]", r"?.split(\1)?[\2]", cleaned)

    # Fix unterminated or long SVG path strings
    cleaned = re.sub(r'd="[^"\n]*$', r'd="M12 4v16m8-8H4"', cleaned, flags=re.MULTILINE)
    cleaned = re.sub(r'd="([^"]{100,})"', r'd="M12 4v16m8-8H4"', cleaned)

    # Normalize component wrapper
    cleaned = ensure_component_wrapper(cleaned)

    return cleaned.strip()


def validate_component(code: str) -> tuple[bool, str]:
    """
    Validate the React component generated by the AI.
    """

    # ==========================================================
    # Empty Response
    # ==========================================================

    if not code or not code.strip():
        return False, "Error: Empty response from AI."

    code = code.strip()

    # ==========================================================
    # Detect Raw Markdown Fences BEFORE stripping them.
    # If the code starts with a code fence, it means the AI
    # returned Markdown rather than plain JSX — reject it.
    # ==========================================================

    if re.search(r"^```", code, re.MULTILINE):
        return (
            False,
            "Error: Markdown code fences detected. "
            "Return plain JSX only, no Markdown.",
        )

    # ==========================================================
    # Root Component Validation
    # ==========================================================

    if not (
        re.search(r"const\s+Component\s*=", code)
        or re.search(r"function\s+Component\s*\(", code)
    ):
        return (
            False,
            "Error: Root component must be named Component.",
        )

    # ==========================================================
    # Return Statement
    # ==========================================================

    if "return" not in code:
        return (
            False,
            "Error: JSX return statement not found.",
        )

    # ==========================================================
    # Import Statements
    # ==========================================================

    if re.search(
        r"^\s*import\s",
        code,
        re.MULTILINE,
    ):
        return (
            False,
            "Error: Import statements are not allowed.",
        )

    # ==========================================================
    # Export Statements
    # ==========================================================

    if re.search(
        r"^\s*export\s",
        code,
        re.MULTILINE,
    ):
        return (
            False,
            "Error: Export statements are not allowed.",
        )

    # ==========================================================
    # Babel AST Validation
    # ==========================================================

    babel_result = validate_with_babel(code)

    if not babel_result.get("valid", False):
        return (
            False,
            "Babel validation failed: "
            f"{babel_result.get('message', 'Unknown error')}",
        )

    # ==========================================================
    # Success
    # ==========================================================

    return (
        True,
        "React component is valid.",
    )


